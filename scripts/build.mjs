import { build } from 'esbuild';
import { chmodSync, mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

// Multi-file bundle for every hikari service.
//
// The old build emitted two monolithic CommonJS bundles (~9.7k lines each),
// which made the generated code impossible to review. This build keeps one
// entry point per service plus shared chunks, so dist mirrors the service
// layout and each file is readable on its own.
//
// `splitting` is an ESM-only esbuild feature, so dist is ESM (`.mjs`) and the
// CommonJS shims below keep `require()`/`node dist/cli.cjs` working through
// Node's require(esm) support (Node >= 22.12, as declared in package.json).
// npm packages stay external: `npm ci` is part of every installation, and
// keeping them out of dist avoids re-bundling third-party code. The vendored
// fflate sources (an in-repository vendored copy, not an npm package) are
// bundled, which is why the bare `fflate` specifier is aliased to that path.

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const outdir = join(root, 'dist');
const fflate = join(root, 'vendor/fflate/src/index.ts');

const entries = [
  { in: join(root, 'services/epub/src/cli.ts'), out: 'cli' },
  { in: join(root, 'services/epub/src/index.ts'), out: 'index' },
  { in: join(root, 'services/ascii/index.ts'), out: 'services/ascii' },
  { in: join(root, 'services/kosync/index.ts'), out: 'services/kosync' },
  { in: join(root, 'services/mobi/index.ts'), out: 'services/mobi' },
  { in: join(root, 'services/epub/src/archive.ts'), out: 'services/archive' },
  { in: fflate, out: 'vendor/fflate' },
];

await build({
  entryPoints: entries,
  outdir,
  outbase: root,
  bundle: true,
  splitting: true,
  format: 'esm',
  platform: 'node',
  target: 'node22',
  outExtension: { '.js': '.mjs' },
  external: ['fast-xml-parser', 'htmlparser2'],
  alias: { fflate },
  logLevel: 'info',
});

// CommonJS shims: `require('dist/index.cjs')` and `node dist/cli.cjs` behave the
// way the Neovim plugin, the npm scripts and third-party callers expect, while
// the implementation stays in the split ESM files.
mkdirSync(join(outdir, 'vendor'), { recursive: true });
const header = '// Generated by scripts/build.mjs. Requires Node >= 22.12 (require(esm)).\n';
writeFileSync(join(outdir, 'index.cjs'),
  `${header}'use strict';\nmodule.exports = require('./index.mjs');\n`);
writeFileSync(join(outdir, 'vendor/fflate.cjs'),
  `${header}'use strict';\nmodule.exports = require('./fflate.mjs');\n`);
writeFileSync(join(outdir, 'cli.cjs'),
  '#!/usr/bin/env node\n' +
  '// Generated by scripts/build.mjs: runs the split ESM entry point.\n' +
  "'use strict';\n" +
  "import('./cli.mjs').catch(error => {\n" +
  '  process.stderr.write(`${JSON.stringify({ ok: false, error: error instanceof Error ? error.message : String(error) })}\\n`);\n' +
  '  process.exitCode = 1;\n' +
  '});\n');
chmodSync(join(outdir, 'cli.cjs'), 0o755);
