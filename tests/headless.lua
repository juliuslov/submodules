-- Run after npm run build:
-- nvim --headless -u NONE -l tests/headless.lua
local root = vim.fn.getcwd()
vim.opt.runtimepath:prepend(root)
dofile(root .. '/plugin/hikari.lua')
local service = require('hikari')
service.setup()
service.register_commands()
local directory = vim.fn.tempname()
vim.fn.mkdir(directory, 'p')
local output = directory .. '/Neovim book.epub'
local function await(start)
  local done, failure, result = false, nil, nil
  start(function(err, data) failure, result, done = err, data, true end)
  assert(vim.wait(60000, function() return done end, 10), 'service request timed out')
  assert(not failure, failure)
  return result
end
local ok, err = pcall(function()
  local epub = require('hikari.epub')
  await(function(cb) epub.export({ title = 'Neovim book', author = 'Tester', language = 'en',
    chapters = { { title = 'Welcome', text = 'Hello from Neovim.' }, { title = 'Next chapter', text = 'A second chapter for reader navigation.' } } }, output, cb) end)
  local info = await(function(cb) epub.inspect(output, cb) end)
  assert(info.title == 'Neovim book')
  local content = await(function(cb) epub.read(output, 0, cb) end)
  assert(content.text:find('Hello from Neovim.', 1, true))
  local buffer = require('hikari.ui').show(info.title, content.text)
  assert(vim.bo[buffer].buftype == 'nofile' and not vim.bo[buffer].modifiable)
  assert(vim.fn.exists(':HikariEpubExport') == 2 and vim.fn.exists(':Hikari') == 2)
  assert(require('wizardo_services') == service)
  assert(await(service.doctor).archive.available)
  assert(vim.fn.exists(':WizMobiConvert') == 2 and vim.fn.exists(':WizMobiInspect') == 2)
  local mobi = require('hikari.mobi')
  local mobi_path, restored_path = directory .. '/book.mobi', directory .. '/restored.epub'
  local converted = await(function(cb) mobi.convert(output, mobi_path, cb) end)
  assert(converted.to == 'mobi' and not converted.lossless)
  assert(await(function(cb) mobi.inspect(mobi_path, cb) end).version == 6)
  await(function(cb) mobi.convert(mobi_path, restored_path, cb) end)
  assert(await(function(cb) epub.inspect(restored_path, cb) end).title == 'Neovim book')
  local image = directory .. '/image.ppm'
  local file = assert(io.open(image, 'wb'))
  file:write('P6\n2 1\n255\n' .. string.char(0, 0, 0, 255, 255, 255)); file:close()
  local ascii = await(function(cb) require('hikari.ascii').convert(image, { width = 2, height = 1, ramp = '@ ' }, cb) end)
  assert(ascii.text == '@ \n')
  local fingerprint = await(function(cb) require('hikari.kosync').document(output, 'binary', cb) end)
  assert(#fingerprint.document == 32 and fingerprint.document:match('^[a-f0-9]+$'))
  assert(vim.fn.exists(':WizKoSyncPull') == 2)
  local Reader = require('hikari.reader')
  local columns, lines, origin = vim.o.columns, vim.o.lines, vim.api.nvim_get_current_win()
  vim.o.columns, vim.o.lines = 140, 42
  local reader = Reader.open(output)
  assert(vim.wait(60000, function() return not reader.busy end, 10), 'reader load timed out')
  assert(not reader.error, reader.error)
  assert(reader.info.title == 'Neovim book' and not reader.geometry.compact)
  assert(vim.api.nvim_win_is_valid(reader.panes.toc.win))
  local background = vim.o.background
  reader:toggle_theme()
  Reader.set_mode('high')
  assert(vim.api.nvim_get_hl(reader.namespace, { name = 'HikariGhostText', link = false }).fg == 0xffffff)
  Reader.set_mode('normal')
  assert(vim.o.background == background, 'reader changed the global colorscheme')
  vim.o.columns, vim.o.lines = 40, 24
  vim.api.nvim_exec_autocmds('VimResized', {})
  assert(reader.geometry.compact and vim.api.nvim_win_get_width(reader.panes.body.win) == 40)
  reader:contents()
  assert(reader.drawer and vim.api.nvim_get_current_win() == reader.panes.toc.win)
  reader:jump(1)
  assert(vim.wait(60000, function() return not reader.busy end, 10))
  assert(not reader.error and reader.text:find('A second chapter', 1, true))
  local body = reader.panes.body.buf
  reader:close()
  assert(Reader.current() == nil and not vim.api.nvim_buf_is_valid(body))
  assert(vim.api.nvim_get_current_win() == origin)
  service.open(mobi_path)
  assert(vim.wait(60000, function()
    local current = Reader.current(); return current and not current.busy
  end, 10), 'MOBI reader load timed out')
  local converted_reader = Reader.current()
  assert(not converted_reader.error and converted_reader.source == mobi_path)
  local temporary_epub = converted_reader.path
  service.close()
  assert(vim.fn.filereadable(temporary_epub) == 0)
  assert(not require('hikari.workspace.startup').eligible(), 'headless startup must not open a workspace')
  local workspace = service.workspace()
  assert(vim.bo[workspace.buf].buftype == 'nofile' and not vim.bo[workspace.buf].modifiable)
  vim.cmd('HikariRefresh')
  service.close()
  assert(not require('hikari.workspace').current())
  assert(not vim.api.nvim_buf_is_valid(workspace.buf))
  vim.o.columns, vim.o.lines = columns, lines
end)
vim.fn.delete(directory, 'rf')
if not ok then io.stderr:write(tostring(err) .. '\n'); vim.cmd('cquit 1') end
print('PASS: headless Neovim EPUB services')
vim.cmd('qa!')
